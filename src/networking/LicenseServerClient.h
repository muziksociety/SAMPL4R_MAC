#pragma once

#include <mutex>
#include <string>

#include <juce_core/juce_core.h>

namespace samplar {

class LicenseServerClient {
public:
    struct ValidationRequest {
        std::string licenseKey;
        std::string hardwareId;
        std::string appVersion;
        std::string userAgent;
        std::string ipAddress;
    };

    struct ValidationResponse {
        bool valid{false};
        juce::var licenseInfo;
        juce::var validationInfo;
        std::string message;
        std::string signedToken;   // SAMPL4R: signed token returned by /api/licenses/validate-token
        int statusCode{0};
    };

    struct ActivationRequest {
        std::string licenseKey;
        std::string hardwareId;
        std::string email;
        std::string password;
    };

    // SAMPL4R first-launch activation (POST /api/licenses/validate-token)
    // Production server does not have /api/v1/validate — validate-token handles
    // both first-time activation AND every-launch revalidation.
    ValidationResponse validateLicense(const ValidationRequest& request);
    ValidationResponse activateLicense(const ActivationRequest& request);

    // SAMPL4R every-launch signed-token check (POST /api/licenses/validate-token)
    ValidationResponse validateToken(const std::string& licenseKey,
                                     const std::string& hardwareId,
                                     const std::string& productId);
    ValidationResponse authenticateWithHardware(const std::string& email,
                                                const std::string& password,
                                                const std::string& hardwareId);

    // New credential-based authentication methods
    ValidationResponse loginWithCredentials(const std::string& email, const std::string& password);
    ValidationResponse activateWithCredentials(const std::string& email, const std::string& password, const std::string& hardwareId);

    // ── Account-based authentication (PRIMARY login path) ─────────────────
    // POST /auth/login-with-hardware { email, password, hardware_id }
    // → { success, license_valid, message, email, license_type, signed_token, ... }
    // The signed_token is generated by license_service.py and is offline-verifiable
    // via SignedTokenVerifier. Cache (email + signed_token) — NEVER the password.
    struct LoginResponse {
        bool        success      { false };
        bool        licenseValid { false };
        std::string message;
        std::string email;
        std::string licenseType;
        std::string signedToken;
        std::string expiresAt;
        juce::var   raw;          // full server payload (for downstream consumers)
        int         statusCode   { 0 };
    };

    LoginResponse loginWithHardware(const std::string& email,
                                    const std::string& password,
                                    const std::string& hardwareId);

    // Deactivation - removes this hardware from license activations
    ValidationResponse deactivateLicense(const std::string& licenseKey, const std::string& hardwareId);

    void setServerUrl(const std::string& url);
    void setTimeout(int timeoutSeconds);
    void setRetryAttempts(int attempts);

private:
    ValidationResponse performPost(const juce::URL& url, const juce::var& payload);
    juce::String createJsonPayload(const juce::var& data) const;
    ValidationResponse parseValidationResponse(const juce::String& responseBody, int statusCode) const;

    std::string serverUrl_ { "https://license-server-n5it.onrender.com" };
    int timeoutSeconds_ { 8 };
    int retryAttempts_ { 2 };
    int retryDelayMs_ { 1000 };

    mutable std::mutex networkMutex_;
};

} // namespace samplar

