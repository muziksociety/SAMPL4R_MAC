/** SAMPLAR brand mark.
 *  Renders the canonical SAMPLAR "S" logo PNG (embedded in BinaryData via
 *  CMake) inside its bounds, preserving aspect ratio and using high-quality
 *  resampling so it stays crisp at every size. The PNG already includes the
 *  motion-blur, gradient and shadow — no painted decoration is added on top. */
class SamplarLogo : public juce::Component
{
public:
    SamplarLogo()
    {
        setInterceptsMouseClicks(false, false);

        // Load embedded PNG once. BinaryData::samplar_logo_png is generated by
        // juce_add_binary_data from assets/samplar_logo.png in CMakeLists.txt.
        if (BinaryData::samplar_logo_pngSize > 0)
            logoImage_ = juce::ImageFileFormat::loadFrom(
                BinaryData::samplar_logo_png,
                BinaryData::samplar_logo_pngSize);
    }

    void paint(juce::Graphics& g) override
    {
        if (!logoImage_.isValid())
        {
            // Fallback: simple white "SAMPLAR" text if the PNG didn't decode.
            g.setColour(juce::Colours::white);
            g.setFont(juce::Font(juce::FontOptions(14.0f).withStyle("Bold")));
            g.drawText("SAMPLAR", getLocalBounds(), juce::Justification::centredLeft);
            return;
        }

        // Draw 20% larger than the component bounds so the logo dominates the
        // top-bar slot. The expanded rect is centered on the component, and
        // drawImageWithin keeps aspect ratio (excess just spills inside the
        // unclipped sibling area, which is empty top-bar background).
        auto natural = getLocalBounds().toFloat();
        auto expanded = natural.withSizeKeepingCentre(natural.getWidth()  * 1.20f,
                                                      natural.getHeight() * 1.20f)
                                .toNearestInt();
        g.drawImageWithin(logoImage_,
                          expanded.getX(), expanded.getY(),
                          expanded.getWidth(), expanded.getHeight(),
                          juce::RectanglePlacement::centred);
    }

private:
    juce::Image logoImage_;
};

/** Big play/stop toggle button — green triangle when stopped, red square when playing. */
class BigPlayButton : public juce::Button
{
public:
    BigPlayButton() : juce::Button("Play") {}

    void setPlaying(bool p)
    {
        if (playing_ == p) return;
        playing_ = p;
        repaint();
    }

    bool isPlaying() const { return playing_; }

    void paintButton(juce::Graphics& g, bool over, bool down) override
    {
        auto bounds = getLocalBounds().toFloat();

        // Background: green when stopped, red when playing
        auto bg = playing_ ? juce::Colour::fromRGB(255, 45, 45)
                           : juce::Colour::fromRGB(0, 220, 118);
        if (down)       bg = bg.darker(0.2f);
        else if (over)  bg = bg.brighter(0.1f);

        g.setColour(bg);
        g.fillRoundedRectangle(bounds, 8.0f);

        // Subtle outer glow
        g.setColour(bg.withAlpha(0.35f));
        g.drawRoundedRectangle(bounds.expanded(2.0f), 10.0f, 1.5f);

        auto cx = bounds.getCentreX();
        auto cy = bounds.getCentreY();
        auto h  = bounds.getHeight() * 0.55f;

        g.setColour(juce::Colours::white);

        if (playing_)
        {
            // Stop icon: white rounded square
            auto sq = juce::Rectangle<float>(0, 0, h * 0.45f, h * 0.45f).withCentre({cx, cy});
            g.fillRoundedRectangle(sq, 2.0f);
        }
        else
        {
            // Play icon: white triangle
            auto w = h * 0.85f;
            juce::Path tri;
            tri.startNewSubPath(cx - w * 0.4f, cy - h * 0.5f);
            tri.lineTo         (cx - w * 0.4f, cy + h * 0.5f);
            tri.lineTo         (cx + w * 0.6f, cy);
            tri.closeSubPath();
            g.fillPath(tri);
        }
    }

private:
    bool playing_ { false };
};

/** Small colored circle showing per-stem load state in the top bar. */
class StemStatusIndicator : public juce::Component
{
public:
    void setColor(juce::Colour c) { color_ = c; repaint(); }
    void setLoaded(bool loaded) { loaded_ = loaded; repaint(); }
    void paint(juce::Graphics& g) override
    {
        auto r = getLocalBounds().toFloat().reduced(2.0f);
        g.setColour(color_.withAlpha(loaded_ ? 0.95f : 0.25f));
        g.fillEllipse(r);
        g.setColour(color_.withAlpha(loaded_ ? 1.0f : 0.5f));
        g.drawEllipse(r, 1.5f);
    }
private:
    juce::Colour color_ { juce::Colours::grey };
    bool loaded_ { false };
};

/** Full-bleed overlay shown when no audio is loaded in S-Mode.
 *  Shows a centered LOAD AUDIO button, plus a "RECENT" list below it
 *  when prior songs exist. Clicking a recent row re-opens that file. */
class LoadAudioOverlay : public juce::Component,
                         private juce::ListBoxModel
{
public:
    LoadAudioOverlay()
    {
        addAndMakeVisible(loadButton_);
        loadButton_.setButtonText("LOAD AUDIO");
        loadButton_.setColour(juce::TextButton::buttonColourId,   juce::Colours::white.withAlpha(0.95f));
        loadButton_.setColour(juce::TextButton::buttonOnColourId, juce::Colours::white);
        loadButton_.setColour(juce::TextButton::textColourOffId,  juce::Colours::black);
        loadButton_.setColour(juce::TextButton::textColourOnId,   juce::Colours::black);
        loadButton_.onClick = [this]() { if (onLoad) onLoad(); };

        addChildComponent(recentLabel_);
        recentLabel_.setText("RECENT", juce::dontSendNotification);
        recentLabel_.setJustificationType(juce::Justification::centred);
        recentLabel_.setColour(juce::Label::textColourId, juce::Colours::white.withAlpha(0.55f));
        recentLabel_.setFont(juce::Font(11.0f, juce::Font::bold).withExtraKerningFactor(0.20f));
        recentLabel_.setInterceptsMouseClicks(false, false);

        addChildComponent(recentList_);
        recentList_.setModel(this);
        recentList_.setRowHeight(44);
        recentList_.setColour(juce::ListBox::backgroundColourId, juce::Colours::transparentBlack);
        recentList_.setColour(juce::ListBox::outlineColourId,    juce::Colours::transparentBlack);

        // Don't intercept mouse on the gray panel itself — only the button + list are clickable
        setInterceptsMouseClicks(false, true);
    }

    void paint(juce::Graphics& g) override
    {
        // Translucent dark-gray fill covering the whole SModePage
        g.fillAll(juce::Colour(0xCC202428));   // ~80% opaque dark grey
    }

    void resized() override
    {
        const int btnW = 240, btnH = 64;
        auto bounds = getLocalBounds();
        auto centre = bounds.getCentre();

        if (recents_.empty())
        {
            // Original button-only layout (perfectly centered)
            loadButton_.setBounds(juce::Rectangle<int>(0, 0, btnW, btnH).withCentre(centre));
            recentLabel_.setVisible(false);
            recentList_.setVisible(false);
            return;
        }

        // Pull button up so the list has space below it
        auto btnCentre = centre.translated(0, -130);
        loadButton_.setBounds(juce::Rectangle<int>(0, 0, btnW, btnH).withCentre(btnCentre));

        const int labelTop = loadButton_.getBottom() + 28;
        const int labelH   = 16;
        const int listW    = juce::jmin(420, bounds.getWidth() - 40);
        const int listH    = juce::jmin(280, (int) recents_.size() * 44 + 6);
        const int listX    = bounds.getCentreX() - listW / 2;

        recentLabel_.setVisible(true);
        recentLabel_.setBounds(listX, labelTop, listW, labelH);

        recentList_.setVisible(true);
        recentList_.setBounds(listX, labelTop + labelH + 6, listW, listH);
    }

    /** Refreshes the recent list. Owner calls this on construction
     *  and after every successful load. */
    void setRecents(const std::vector<juce::File>& recents)
    {
        recents_ = recents;
        recentList_.updateContent();
        recentList_.repaint();
        resized();
    }

    std::function<void()>                    onLoad;
    std::function<void(const juce::File&)>   onLoadRecent;

private:
    // ── ListBoxModel ─────────────────────────────────────────────
    int getNumRows() override { return (int) recents_.size(); }

    void paintListBoxItem(int rowNumber, juce::Graphics& g,
                          int width, int height, bool rowIsSelected) override
    {
        if (rowNumber < 0 || rowNumber >= (int) recents_.size()) return;
        const auto& f = recents_[(size_t) rowNumber];
        const bool exists = f.existsAsFile();

        auto r = juce::Rectangle<int>(0, 0, width, height).reduced(4, 3);

        // Background: subtle cyan tint on selection/hover
        if (rowIsSelected)
            g.setColour(juce::Colour::fromRGB(0, 80, 110).withAlpha(0.55f));
        else
            g.setColour(juce::Colours::white.withAlpha(0.04f));
        g.fillRoundedRectangle(r.toFloat(), 4.0f);

        const float topAlpha    = exists ? 1.0f  : 0.45f;
        const float bottomAlpha = exists ? 0.65f : 0.35f;

        auto topRow    = r.removeFromTop(22).reduced(10, 0);
        auto bottomRow = r.reduced(10, 0);

        // Top: file basename (bold white)
        g.setColour(juce::Colours::white.withAlpha(topAlpha));
        g.setFont(juce::Font(15.0f, juce::Font::bold));
        auto title = f.getFileNameWithoutExtension();
        if (!exists) title << " (missing)";
        g.drawText(title, topRow, juce::Justification::centredLeft, true);

        // Bottom: parent folder path (dim, ellipsized right)
        g.setColour(juce::Colours::white.withAlpha(bottomAlpha));
        g.setFont(juce::Font(11.0f));
        auto parent = f.getParentDirectory().getFullPathName();
        g.drawText(parent, bottomRow, juce::Justification::centredLeft, true);
    }

    void listBoxItemClicked(int rowNumber, const juce::MouseEvent&) override
    {
        if (rowNumber < 0 || rowNumber >= (int) recents_.size()) return;
        const auto f = recents_[(size_t) rowNumber];

        if (!f.existsAsFile())
        {
            // Prune missing entries on click and refresh display
            juce::Logger::writeToLog("[LoadAudioOverlay] missing recent pruned: "
                                     + f.getFullPathName());
            samplar::RecentSongs::remove(f);
            // Pruning here gives instant feedback; the owner will also
            // re-call setRecents on the next external event.
            for (auto it = recents_.begin(); it != recents_.end(); )
                if (it->getFullPathName().equalsIgnoreCase(f.getFullPathName()))
                    it = recents_.erase(it);
                else ++it;
            recentList_.updateContent();
            recentList_.repaint();
            resized();
            return;
        }

        if (onLoadRecent) onLoadRecent(f);
    }

    juce::TextButton           loadButton_;
    juce::Label                recentLabel_;
    juce::ListBox              recentList_;
    std::vector<juce::File>    recents_;
};

