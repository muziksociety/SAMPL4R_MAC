"""
Windows-TTS proof-of-concept for SM5 tutorial automation.

Reads resources/mentor/mentor_lessons.json, picks a lesson by id (default:
gs_welcome), and generates one WAV per step under tools/tutorial_gen/out/<lesson>/

Usage:
    python tools/tutorial_gen/tts_windows.py
    python tools/tutorial_gen/tts_windows.py --lesson gs_welcome --voice "Microsoft Zira Desktop" --rate 0
    python tools/tutorial_gen/tts_windows.py --lang es --lesson gs_welcome
    python tools/tutorial_gen/tts_windows.py --list-voices

Audio is generated by SAPI 5 via PowerShell — no extra deps, no API key, no
network. Output is mono 22.05 kHz PCM (SAPI default) which we will upsample/mux
later in the pipeline.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
LESSONS_JSON = REPO_ROOT / "resources" / "mentor" / "mentor_lessons.json"
OUT_DIR = REPO_ROOT / "tools" / "tutorial_gen" / "out"


def load_lesson(lesson_id: str) -> tuple[dict, dict]:
    """Return (section, lesson) by id. Raises if not found."""
    data = json.loads(LESSONS_JSON.read_text(encoding="utf-8"))
    for sec in data.get("sections", []):
        for les in sec.get("lessons", []):
            if les["id"] == lesson_id:
                return sec, les
    raise SystemExit(f"Lesson '{lesson_id}' not found in {LESSONS_JSON}")


def text_for_step(step: dict, lang: str) -> str:
    title = step.get("title_es" if lang == "es" else "title", "")
    body = step.get("body_es" if lang == "es" else "body", "")
    if lang == "es" and not (step.get("title_es") and step.get("body_es")):
        title = step.get("title", title)
        body = step.get("body", body)
    body = re.sub(r"\n+", ". ", body).strip()
    return f"{title}. {body}"


def list_voices() -> None:
    ps = (
        "Add-Type -AssemblyName System.Speech;"
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer;"
        "$s.GetInstalledVoices() | ForEach-Object { $_.VoiceInfo | "
        "Select-Object Name, Culture, Gender, Age | Format-Table -AutoSize | Out-String }"
    )
    res = subprocess.run(
        ["powershell", "-NoProfile", "-Command", ps],
        capture_output=True, text=True, check=False,
    )
    sys.stdout.write(res.stdout or res.stderr)


def synthesize(text: str, out_wav: Path, voice: str | None, rate: int) -> None:
    """Generate WAV via SAPI 5 driven by PowerShell."""
    out_wav.parent.mkdir(parents=True, exist_ok=True)
    # Pass text via stdin to handle long bodies without command-line size issues.
    voice_clause = (
        f"$s.SelectVoice('{voice.replace(chr(39), chr(39)*2)}');" if voice else ""
    )
    ps_script = (
        "Add-Type -AssemblyName System.Speech;"
        "$text = [Console]::In.ReadToEnd();"
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer;"
        f"{voice_clause}"
        f"$s.Rate = {rate};"
        f"$s.SetOutputToWaveFile('{str(out_wav).replace(chr(92), chr(92)*2)}');"
        "$s.Speak($text);"
        "$s.Dispose();"
    )
    proc = subprocess.run(
        ["powershell", "-NoProfile", "-Command", ps_script],
        input=text, capture_output=True, text=True, check=False,
    )
    if proc.returncode != 0 or not out_wav.exists():
        raise RuntimeError(
            f"SAPI failed for {out_wav.name}:\n{proc.stderr or proc.stdout}"
        )


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--lesson", default="gs_welcome", help="Lesson id to render.")
    p.add_argument("--lang", default="en", choices=("en", "es"))
    p.add_argument("--voice", default=None,
                   help="SAPI voice name (e.g. 'Microsoft Zira Desktop'). Omit for default.")
    p.add_argument("--rate", type=int, default=0,
                   help="-10 (slow) to 10 (fast). 0 default.")
    p.add_argument("--list-voices", action="store_true")
    args = p.parse_args()

    if args.list_voices:
        list_voices()
        return

    sec, lesson = load_lesson(args.lesson)
    out_root = OUT_DIR / args.lesson / args.lang
    print(f"Lesson: {sec['id']} / {lesson['id']} -> {out_root}")
    out_root.mkdir(parents=True, exist_ok=True)

    manifest = []
    for idx, step in enumerate(lesson["steps"]):
        text = text_for_step(step, args.lang)
        wav = out_root / f"step_{idx:02d}.wav"
        print(f"  step {idx:02d}: {step.get('title', '')[:60]}")
        synthesize(text, wav, args.voice, args.rate)
        manifest.append({
            "index": idx,
            "title": step.get("title_es" if args.lang == "es" else "title", ""),
            "wav": wav.name,
            "size_bytes": wav.stat().st_size,
        })

    (out_root / "manifest.json").write_text(
        json.dumps({
            "section_id": sec["id"],
            "lesson_id": lesson["id"],
            "lang": args.lang,
            "voice": args.voice or "<default>",
            "rate": args.rate,
            "steps": manifest,
        }, indent=2),
        encoding="utf-8",
    )
    print(f"Done. Manifest: {out_root / 'manifest.json'}")


if __name__ == "__main__":
    main()
